export function buildNutritionContextBlock({
  userProfileSummary = "",
  memorySummary = "",
  mealInfoSummary = "",
} = {}) {
  const parts = [
    "[CONTEXT - USE AS SUPPORT ONLY]",
    `- User profile summary: ${String(userProfileSummary || "none").slice(0, 1200)}`,
    `- Memory summary: ${String(memorySummary || "none").slice(0, 1200)}`,
    `- Meal information summary (application-calculated): ${String(mealInfoSummary || "none").slice(0, 1200)}`,
  ];

  return parts.join("\n");
}
